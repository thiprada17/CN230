COMMENT ON TABLE flow IS
'กำหนด material_id หรือ product_id ได้อย่างใดอย่างหนึ่ง หรือไม่กำหนดทั้งคู่สำหรับ resource/emission ทั่วไป';

COMMENT ON COLUMN production_batch.production_year IS
'Optional production year when a specific calendar date is unavailable.';
COMMENT ON COLUMN production_batch.area_ha IS
'Optional cultivated area in hectares; NULL when not reported.';
