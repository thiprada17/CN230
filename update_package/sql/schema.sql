-- Agri LCI Database - Schema
-- Scope: Food & Agro-processing
-- PostgreSQL 17+
-- Fresh database only.

CREATE TABLE product_category (
    category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) UNIQUE NOT NULL,
    description TEXT
);

CREATE TABLE unit (
    unit_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_name VARCHAR(80) NOT NULL,
    unit_symbol VARCHAR(20) NOT NULL UNIQUE,
    unit_type VARCHAR(50) NOT NULL,
    base_unit_id INT,
    conversion_factor_to_base DECIMAL(18,8) NOT NULL DEFAULT 1
);

CREATE TABLE product (
    product_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(150) NOT NULL,
    category_id INT NOT NULL REFERENCES product_category(category_id),
    description TEXT,
    unit_id INT NOT NULL REFERENCES unit(unit_id)
);

CREATE TABLE material (
    material_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_name VARCHAR(150) NOT NULL,
    material_type VARCHAR(80) NOT NULL,
    unit_id INT NOT NULL REFERENCES unit(unit_id),
    description TEXT
);

CREATE TABLE location (
    location_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province VARCHAR(100),
    district VARCHAR(100),
    country VARCHAR(100) NOT NULL,
    latitude DECIMAL(10,7),
    longitude DECIMAL(10,7)
);

CREATE TABLE supplier (
    supplier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR(150) NOT NULL,
    location_id INT NOT NULL REFERENCES location(location_id),
    supplier_type VARCHAR(80),
    contact_info TEXT
);

CREATE TABLE data_source (
    source_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_name VARCHAR(200) NOT NULL,
    document_name VARCHAR(255) NOT NULL,
    publication_year INT NOT NULL,
    reference_url TEXT NOT NULL,
    access_date DATE
);

CREATE TABLE material_supplier (
    material_supplier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id INT NOT NULL REFERENCES material(material_id),
    supplier_id INT NOT NULL REFERENCES supplier(supplier_id),
    source_id INT NOT NULL REFERENCES data_source(source_id),
    CONSTRAINT uq_material_supplier_source UNIQUE (material_id, supplier_id, source_id)
);

CREATE TABLE process (
    process_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_name VARCHAR(150) NOT NULL,
    description TEXT
);

CREATE TABLE process_step (
    step_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id INT NOT NULL REFERENCES process(process_id),
    step_name VARCHAR(150) NOT NULL,
    step_order INT NOT NULL CHECK (step_order > 0),
    description TEXT,
    CONSTRAINT uq_process_step_order UNIQUE (process_id, step_order)
);

-- Date may be unavailable in literature-based datasets.
-- production_year and area_ha are optional metadata.
CREATE TABLE production_batch (
    batch_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INT NOT NULL REFERENCES product(product_id),
    production_date DATE,
    production_quantity DECIMAL(18,6) NOT NULL CHECK (production_quantity >= 0),
    unit_id INT NOT NULL REFERENCES unit(unit_id),
    location_id INT NOT NULL REFERENCES location(location_id),
    production_year INT CHECK (production_year IS NULL OR production_year BETWEEN 1900 AND 2100),
    area_ha NUMERIC(18,6) CHECK (area_ha IS NULL OR area_ha > 0)
);

CREATE TABLE batch_process (
    batch_process_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id INT NOT NULL REFERENCES production_batch(batch_id),
    step_id INT NOT NULL REFERENCES process_step(step_id),
    execution_order INT NOT NULL CHECK (execution_order > 0),
    location_id INT NOT NULL REFERENCES location(location_id),
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT uq_batch_process_order UNIQUE (batch_id, execution_order),
    CONSTRAINT chk_batch_process_time CHECK (
        completed_at IS NULL OR started_at IS NULL OR completed_at >= started_at
    )
);

CREATE TABLE flow (
    flow_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flow_name VARCHAR(150) NOT NULL,
    flow_type VARCHAR(50) NOT NULL,
    material_id INT REFERENCES material(material_id),
    product_id INT REFERENCES product(product_id),
    unit_id INT NOT NULL REFERENCES unit(unit_id),
    CONSTRAINT chk_flow_single_entity CHECK (
        NOT (material_id IS NOT NULL AND product_id IS NOT NULL)
    )
);

CREATE TABLE lci_exchange (
    exchange_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_process_id INT NOT NULL REFERENCES batch_process(batch_process_id),
    flow_id INT NOT NULL REFERENCES flow(flow_id),
    exchange_type VARCHAR(20) NOT NULL CHECK (exchange_type IN ('INPUT', 'OUTPUT')),
    amount DECIMAL(18,6) NOT NULL CHECK (amount >= 0),
    unit_id INT NOT NULL REFERENCES unit(unit_id),
    source_id INT NOT NULL REFERENCES data_source(source_id),
    data_year INT,
    data_period_start INT,
    data_period_end INT,
    CONSTRAINT chk_lci_exchange_data_period CHECK (
        (
            data_year IS NOT NULL
            AND data_period_start IS NULL
            AND data_period_end IS NULL
        )
        OR
        (
            data_year IS NULL
            AND data_period_start BETWEEN 1900 AND 2100
            AND data_period_end BETWEEN data_period_start AND 2100
        )
    )
);

CREATE TABLE environment_impact (
    impact_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_process_id INT NOT NULL REFERENCES batch_process(batch_process_id),
    impact_type VARCHAR(100) NOT NULL,
    impact_amount DECIMAL(18,6) NOT NULL CHECK (impact_amount >= 0),
    unit_id INT NOT NULL REFERENCES unit(unit_id),
    source_id INT NOT NULL REFERENCES data_source(source_id),
    data_year INT NOT NULL
);

ALTER TABLE unit
    ADD CONSTRAINT fk_unit_base_unit
    FOREIGN KEY (base_unit_id) REFERENCES unit(unit_id);

ALTER TABLE unit
    ADD CONSTRAINT chk_unit_conversion_positive
    CHECK (conversion_factor_to_base > 0);

CREATE TABLE study_impact (
    study_impact_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id INT NOT NULL REFERENCES data_source(source_id),
    product_id INT NOT NULL REFERENCES product(product_id),
    impact_type VARCHAR(100) NOT NULL,
    impact_amount DECIMAL(18,12) NOT NULL CHECK (impact_amount >= 0),
    unit_id INT NOT NULL REFERENCES unit(unit_id),
    functional_unit_quantity DECIMAL(18,6) NOT NULL CHECK (functional_unit_quantity > 0),
    functional_unit_unit_id INT NOT NULL REFERENCES unit(unit_id),
    location_id INT REFERENCES location(location_id),
    impact_method VARCHAR(150),
    data_year INT,
    system_boundary TEXT,
    notes TEXT
);

